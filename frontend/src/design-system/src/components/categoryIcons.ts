function plain(value: string): string {
  return (value || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
}

/** Até `max` ícones sugeridos para um nome de categoria. Vazio quando nada combina. */
export function suggestCategoryIcons(name: string, max = 3): CategoryIconName[] {
  const n = ' ' + plain(name).replace(/[^a-z0-9]+/g, ' ');
  const out: CategoryIconName[] = [];
  if (n.trim().length < 3) return out;
  for (const [key, words] of RULES) {
    if (!out.includes(key) && words.some((word) => n.includes(' ' + word))) out.push(key);
  }
  return out.slice(0, max);
}

export function suggestCategoryIcon(name: string): CategoryIconName | null {
  return suggestCategoryIcons(name, 1)[0] ?? null;
}

export function isCategoryIcon(value: unknown): value is CategoryIconName {
  return typeof value === 'string' && value in CATEGORY_ICONS;
}

export function matchesIconQuery(key: CategoryIconName, query: string): boolean {
  const it = CATEGORY_ICONS[key];
  return plain(it.label + ' ' + it.group).includes(plain(query));
}

/** Luminância relativa de uma cor hex, para escolher texto escuro ou claro sobre ela. */
export function luminance(hex: string): number {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex);
  if (!m) return 0.5;
  const n = parseInt(m[1], 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function inkOn(hex: string): string {
  return luminance(hex) > 0.3 ? '#08201f' : '#ffffff';
}
